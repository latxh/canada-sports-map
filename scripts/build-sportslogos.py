#!/usr/bin/env python3
"""
Turn the SportsLogos.net downloads (scripts/fetch-sportslogos.py) into web-sized images in
public/sportslogos/<team>/ and the typed list in src/data/sportslogos.ts.

Needs ImageMagick (`magick`). Images are used with SportsLogos.net's permission and credited
on every card and in Credits.

  SLN_DIR=/tmp/sln python3 scripts/build-sportslogos.py
"""
import json
import os
import re
import shutil
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SLN = os.environ.get('SLN_DIR', '/tmp/sln')
OUT = os.path.join(ROOT, 'public', 'sportslogos')
DATA = os.path.join(ROOT, 'src', 'data', 'sportslogos.ts')

# SportsLogos.net dates winter-sport seasons by the year they end (1995–96 is "1996");
# the atlas dates seasons by the year they start, so shift the start back a year.
WINTER = {'NHL', 'NBA', 'NLL', 'PWHL'}
# Longest side in pixels: about twice the size the cards show them at; the -lg copy is for the lightbox.
SIZE = {'logo': 360, 'home': 420, 'away': 420, 'surface': 640}
LARGE = 1200


def main():
    items = json.load(open(os.path.join(SLN, 'items.json')))
    index = json.load(open(os.path.join(SLN, 'index.json')))
    league = {t['id']: t['league'] for t in index['teams']}
    team_pages = {**index['matched']}
    shutil.rmtree(OUT, ignore_errors=True)
    out = {}
    for it in items:
        if not it.get('file'):
            continue
        team, kind = it['team'], it['kind']
        src = os.path.join(SLN, it['file'])
        slug = it['view'].split('/logos/view/')[1].split('/')[0][:12]
        rel = f"{team}/{kind}-{it['slnFrom'] or 0}-{slug}.webp"
        dest = os.path.join(OUT, rel)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        size = SIZE[kind]
        # Older images sit on a white box: clear white that touches the edges, so they read on
        # dark cards too (white inside the artwork is left alone).
        clear = []
        if kind != 'surface':
            clear = ['-alpha', 'set', '-bordercolor', 'white', '-border', '1', '-fuzz', '6%', '-fill', 'none', '-draw', 'color 0,0 floodfill', '-shave', '1x1']
        for out_path, px in ((dest, size), (dest[: -len('.webp')] + '-lg.webp', LARGE)):
            subprocess.run(
                ['magick', src + '[0]', *clear, '-trim', '+repage', '-background', 'none', '-resize', f'{px}x{px}>', '-strip', '-quality', '82', '-define', 'webp:alpha-quality=90', out_path],
                check=True,
            )
        w, h = map(int, subprocess.run(['magick', 'identify', '-format', '%w %h', dest], check=True, capture_output=True, text=True).stdout.split())
        start, end = it['slnFrom'], it['slnTo']
        if start and league.get(team) in WINTER:
            start -= 1
        # The image's own label on SportsLogos.net, minus the team name and years.
        label = re.sub(r'\s*\(.*\)$', '', it['title'])
        out.setdefault(team, {'page': None, 'logos': [], 'home': [], 'away': [], 'surfaces': []})
        entry = {'file': rel, 'from': start or 0, 'to': end, 'page': it['view'], 'label': label, 'w': w, 'h': h}
        key = {'logo': 'logos', 'home': 'home', 'away': 'away', 'surface': 'surfaces'}[kind]
        out[team][key].append(entry)
    names = {t['id']: t['name'] for t in index['teams']}
    hrefs = {}
    for it in items:
        hrefs.setdefault(it['team'], []).append(it['slnTeam'])
    for team, entry in out.items():
        # The team's page under its current name when it has several (e.g. Eskimos, then Elks).
        pages = sorted(set(hrefs.get(team, []) + team_pages.get(team, [])))
        slug = re.sub(r'[^a-z0-9]+', '-', names.get(team, '').lower().replace('é', 'e')).strip('-')
        best = next((h for h in pages if slug and slug in h.lower().replace('é', 'e')), pages[0] if pages else None)
        entry['page'] = 'https://www.sportslogos.net' + best if best else None
        for key in ('logos', 'home', 'away', 'surfaces'):
            entry[key].sort(key=lambda e: (e['from'], e['to'] or 9999))

    def image(e):
        to = f", to: {e['to']}" if e['to'] else ''
        return f"{{file: {json.dumps(e['file'])}, from: {e['from']}{to}, width: {e['w']}, height: {e['h']}, page: {json.dumps(e['page'])}, label: {json.dumps(e['label'], ensure_ascii=False)}}}"

    lines = [
        '/**',
        ' * Logo, uniform and playing-surface history from SportsLogos.net, used with permission and',
        ' * credited on every card (and in Credits). Generated by scripts/build-sportslogos.py from',
        ' * scripts/fetch-sportslogos.py downloads; images in public/sportslogos/. Years follow the',
        ' * atlas (a season is dated by the year it starts).',
        ' */',
        '',
        'export interface SlnImage {',
        '  /** Path under public/sportslogos/ (the lightbox uses the same name with -lg). */',
        '  file: string;',
        '  from: number;',
        '  to?: number;',
        '  /** Pixel size of the web image. */',
        '  width: number;',
        '  height: number;',
        '  /** The image page on SportsLogos.net. */',
        '  page: string;',
        '  /** Its title there, e.g. "Toronto Raptors Primary Logo". */',
        '  label: string;',
        '}',
        '',
        'export interface SlnTeam {',
        '  /** The team on SportsLogos.net. */',
        '  page: string;',
        '  logos: SlnImage[];',
        '  home: SlnImage[];',
        '  away: SlnImage[];',
        '  surfaces: SlnImage[];',
        '}',
        '',
        'export const SPORTSLOGOS: Record<string, SlnTeam> = {',
    ]
    for team in sorted(out):
        e = out[team]
        lines.append(f'  {json.dumps(team)}: {{')
        lines.append(f"    page: {json.dumps(e['page'])},")
        for key in ('logos', 'home', 'away', 'surfaces'):
            if e[key]:
                lines.append(f'    {key}: [')
                lines.extend(f'      {image(i)},' for i in e[key])
                lines.append('    ],')
            else:
                lines.append(f'    {key}: [],')
        lines.append('  },')
    lines.append('};')
    lines.append('')
    open(DATA, 'w').write('\n'.join(lines))
    total = sum(len(e[k]) for e in out.values() for k in ('logos', 'home', 'away', 'surfaces'))
    print(f'{total} images for {len(out)} teams -> public/sportslogos/, src/data/sportslogos.ts')


if __name__ == '__main__':
    main()
